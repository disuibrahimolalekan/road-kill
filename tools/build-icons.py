def build_block():
    rows = ['<symbol id="i-%s" viewBox="0 0 24 24">%s</symbol>' % (k, v)
            for k, v in ICONS.items()]
    return (START + '\n'
            '<svg id="iconSprite" aria-hidden="true" focusable="false" '
            'style="position:absolute;width:0;height:0;overflow:hidden">\n'
            + '\n'.join(rows) + '\n</svg>\n' + END)


def write_html():
    src = open(HTML, encoding='utf-8').read()
    block = build_block()
    if START in src and END in src:
        new = re.sub(re.escape(START) + r'.*?' + re.escape(END),
                     lambda _: block, src, flags=re.S)
    else:
        # first run: drop it in just before the module script
        anchor = '<script type="module" src="/src/main.js"></script>'
        if anchor not in src:
            sys.exit('anchor not found and no ICONS markers present')
        new = src.replace(anchor, block + '\n' + anchor, 1)
    if new != src:
        open(HTML, 'w', encoding='utf-8').write(new)
        print(f'  wrote {len(ICONS)} symbols into {os.path.relpath(HTML, REPO)}')
    else:
        print(f'  sprite already up to date ({len(ICONS)} symbols)')


def check_usage():
    """Every icon referenced in index.html or src/*.js must resolve to a symbol.

    Two forms are scanned: literal `<use href="#i-name">` in markup, and the
    `icon('name')` / `icon("name")` helper calls in JS. A call with a computed
    name (icon(var)) is reported rather than guessed at.
    """
    refs, missing, dynamic = {}, [], []
    pats = [re.compile(r'#i-([a-z]+)'), re.compile(r"icon\(\s*'([a-z]+)'"),
            re.compile(r'icon\(\s*"([a-z]+)"'),
            # weapon definitions carry the sprite name as a value:
            #   icon:'rocket'   -> only reachable via icon(def.icon)
            re.compile(r"icon\s*:\s*'([a-z]+)'"), re.compile(r'icon\s*:\s*"([a-z]+)"')]
    dyn = re.compile(r"icon\(\s*(?!['\"])([A-Za-z_$])")
    for f in [HTML] + sorted(glob.glob(os.path.join(REPO, 'src', '*.js'))):
        if f.endswith('.bak'):
            continue
        try:
            txt = open(f, encoding='utf-8').read()
        except OSError:
            continue
        rel = os.path.relpath(f, REPO)
        names = set()
        for pat in pats:
            names |= set(pat.findall(txt))
        for name in sorted(names):
            refs.setdefault(rel, set()).add(name)
            if name not in ICONS:
                missing.append(f'{rel} -> #{name}')
        for m in dyn.finditer(txt):
            if '.icon' in txt[max(0, m.start() - 40):m.start()]:
                continue                      # icon(def.icon) -> dynamic, fine
            if re.search(r'function\s+$', txt[max(0, m.start() - 12):m.start()]):
                continue                      # the icon() definition itself
            dynamic.append(f'{rel} -> {m.group(0)}')
    if missing:
        print('  MISSING symbols:')
        for m in missing:
            print('    ' + m)
        return False
    used = set().union(*refs.values()) if refs else set()
    print(f'  all {len(used)} referenced icons resolve '
          f'({sum(len(v) for v in refs.values())} call sites)')
    if dynamic:
        print('  dynamic names (verify by hand): ' + ', '.join(dynamic))
    unused = sorted(set(ICONS) - used)
    if unused:
        print('  defined but never referenced: ' + ', '.join(unused))
    return True


if __name__ == '__main__':
    write_html()
    ok = check_usage()
    sys.exit(0 if ok else 1)
